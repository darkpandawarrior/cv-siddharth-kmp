package com.siddharth.cv.shared.data

/**
 * Screenshot galleries, fetched over the network from the live React site rather than bundled.
 *
 * **Why network and not `composeResources`.** 166 screenshots would add megabytes to a wasm bundle
 * whose framework floor is already 2.6 MB brotli, and every byte would be paid on first paint even
 * by a visitor who never opens a project page. Fetched, they cost nothing until scrolled to, and
 * the daily `refresh-media.yml` job on the React repo keeps them current for free — this port
 * inherits that automation instead of duplicating it.
 *
 * **Why `.webp` and not `.avif`.** The site publishes every shot in avif, webp and png. Skiko's
 * bundled codec set (verified against the shipped wasm: jpeg, png, gif, ico, webp, wbmp) has NO
 * avif decoder, so an avif URL decodes to nothing with no error worth reading. The React site
 * publishes a webp sibling beside every avif, so preferring webp sidesteps the gap entirely at no
 * cost in fidelity. No pair tally here on purpose: it counts files in the other repo, nothing in
 * this build can check it, and the last one shipped was off by 253.
